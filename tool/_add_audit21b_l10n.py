LOCALES = ['de', 'en', 'ru', 'tr', 'ar']

for loc in LOCALES:
    path = ARB_DIR / f'app_{loc}.arb'
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    added = 0
    for k, v in KEYS[loc].items():
        if k not in data:
            data[k] = v
            added += 1
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')
    print(f'{loc}: added {added} keys (total {len(data)})')

print('Done.')
